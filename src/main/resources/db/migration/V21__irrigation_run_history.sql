-- penyiraman disimpan backend untuk melacak error. Kolom last_* di irrigation_schedule ditimpa setiap jalan;
-- tabel ini menyimpan setiap sesi siram, termasuk yang tidak sempat mengirim perintah (MISSED, SKIPPED, WAITING).
CREATE TABLE irrigation_run (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_date               DATE         NOT NULL,
    irrigation_schedule_id BIGINT,
    scheduled_time         TIME         NOT NULL,
    result                 VARCHAR(16)  NOT NULL,
    reason_code            VARCHAR(64),
    message                VARCHAR(500),
    duration_seconds       INTEGER,
    command_uid            VARCHAR(64),
    recorded_at            TIMESTAMPTZ  NOT NULL,
    created_at             TIMESTAMPTZ  NOT NULL,
    updated_at             TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_irrigation_run_schedule FOREIGN KEY (irrigation_schedule_id)
        REFERENCES irrigation_schedule (id) ON DELETE SET NULL
);

CREATE INDEX ix_irrigation_run_date ON irrigation_run (run_date DESC, id DESC);
CREATE INDEX ix_irrigation_run_schedule_date ON irrigation_run (irrigation_schedule_id, run_date);

COMMENT ON TABLE irrigation_run IS 'Riwayat sesi siram terjadwal; satu baris per jadwal per tanggal (WAITING diperbarui setelah pemupukan).';
COMMENT ON COLUMN irrigation_run.scheduled_time IS 'Jam jadwal saat itu (tetap ada walau jadwalnya dihapus atau diubah).';
COMMENT ON COLUMN irrigation_run.result IS 'STARTED, SKIPPED (ditolak aturan keselamatan), FAILED, MISSED (backend mati), WAITING (menunggu pemupukan).';
COMMENT ON COLUMN irrigation_run.command_uid IS 'Perintah ke pompa siram; status ACK/gagal dari alat ada di actuator_command.';

-- Hasil terakhir yang sudah tercatat sebelum tabel ini ada.
INSERT INTO irrigation_run (run_date, irrigation_schedule_id, scheduled_time, result, reason_code, message,
                            duration_seconds, command_uid, recorded_at, created_at, updated_at)
SELECT last_run_date, id, time_of_day, last_result, last_reason_code, last_message,
       last_duration_seconds, last_command_uid, last_run_at, last_run_at, last_run_at
FROM irrigation_schedule
WHERE last_result IS NOT NULL AND last_run_date IS NOT NULL AND last_run_at IS NOT NULL;
