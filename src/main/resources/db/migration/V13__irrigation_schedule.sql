-- Jadwal siram harian (keputusan 29 Okt 2026: penjadwalan siram dikerjakan backend; jam diisi lewat aplikasi).
--
-- Sementara murni terjadwal: setiap hari pada time_of_day (zona kebun, WIB) backend mengirim perintah ON
-- berdurasi ke pompa siram, lewat jalur perintah biasa sehingga semua interlock tetap berlaku. last_* mencatat
-- putaran terakhir supaya satu jadwal tidak berjalan dua kali sehari dan petani bisa melihat hasilnya.
CREATE TABLE irrigation_schedule (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time_of_day      TIME         NOT NULL,
    duration_seconds INTEGER      NOT NULL,
    enabled          BOOLEAN      NOT NULL DEFAULT TRUE,
    notes            VARCHAR(255),
    last_run_date    DATE,
    last_run_at      TIMESTAMPTZ,
    last_result      VARCHAR(16),
    last_message     VARCHAR(500),
    last_command_uid VARCHAR(64),
    created_at       TIMESTAMPTZ  NOT NULL,
    updated_at       TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_irrigation_schedule_time UNIQUE (time_of_day),
    CONSTRAINT ck_irrigation_schedule_duration CHECK (duration_seconds > 0)
);

COMMENT ON COLUMN irrigation_schedule.time_of_day IS 'Jam siram dalam zona kebun (app.cultivation.zone, WIB).';
COMMENT ON COLUMN irrigation_schedule.last_run_date IS 'Tanggal (zona kebun) putaran terakhir; jadwal berjalan paling banyak sekali per tanggal.';
COMMENT ON COLUMN irrigation_schedule.last_result IS 'STARTED, SKIPPED (ditolak aturan keselamatan), FAILED, MISSED (backend mati saat jadwal).';
