-- Fase 1: siklus tanam, fase pertumbuhan (HST), tanaman perlakuan, pengamatan.
--
-- Protokol-Data.md §2 mengubah keputusan terbuka "apakah tanaman dilacak satu per satu?" menjadi
-- "ya": 48 tanaman perlakuan (K0 / N- / P- / K-) dalam 4 blok harus punya identitas, dan tiap 3-4
-- hari dicatat tinggi, jumlah daun, ukuran daun ke-3, serta pembacaan tanah galonnya. HST (hari
-- setelah transplant) dan fase pertumbuhan dibutuhkan fuzzy dosing (Arsitektur-Sistem.md §12).
--
-- Semua angka agronomi (batas HST, EC target, rasio N:P:K) adalah DATA di growth_phase, bukan kode.

-- ---------------------------------------------------------------------------
-- Siklus tanam
-- ---------------------------------------------------------------------------
CREATE TABLE planting_cycle (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                  VARCHAR(64)   NOT NULL,
    name                  VARCHAR(128)  NOT NULL,
    variety               VARCHAR(128),
    transplant_date       DATE          NOT NULL,
    expected_harvest_date DATE,
    ended_at              DATE,
    status                VARCHAR(16)   NOT NULL DEFAULT 'ACTIVE',
    notes                 VARCHAR(1000),
    created_at            TIMESTAMPTZ   NOT NULL,
    updated_at            TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uk_planting_cycle_code UNIQUE (code)
);

COMMENT ON TABLE planting_cycle IS 'Satu musim tanam. HST = hari sejak transplant_date (zona waktu Asia/Jakarta).';
COMMENT ON COLUMN planting_cycle.status IS 'PLANNED / ACTIVE / ENDED. Hanya satu siklus ACTIVE pada satu waktu.';

-- Hanya satu siklus aktif: HST dan fase "hari ini" harus punya satu jawaban.
CREATE UNIQUE INDEX uk_planting_cycle_single_active ON planting_cycle (status) WHERE status = 'ACTIVE';

-- ---------------------------------------------------------------------------
-- Fase pertumbuhan per siklus
-- ---------------------------------------------------------------------------
CREATE TABLE growth_phase (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id      BIGINT        NOT NULL,
    code          VARCHAR(32)   NOT NULL,
    name          VARCHAR(128)  NOT NULL,
    start_hst     INTEGER       NOT NULL,
    end_hst       INTEGER,
    ec_target_min NUMERIC(6, 3),
    ec_target_max NUMERIC(6, 3),
    ratio_n       NUMERIC(6, 2),
    ratio_p       NUMERIC(6, 2),
    ratio_k       NUMERIC(6, 2),
    notes         VARCHAR(500),
    created_at    TIMESTAMPTZ   NOT NULL,
    updated_at    TIMESTAMPTZ   NOT NULL,
    CONSTRAINT fk_phase_cycle FOREIGN KEY (cycle_id) REFERENCES planting_cycle (id) ON DELETE CASCADE,
    CONSTRAINT uk_phase_cycle_code UNIQUE (cycle_id, code)
);

COMMENT ON COLUMN growth_phase.end_hst IS 'Inklusif. NULL = sampai siklus berakhir.';
COMMENT ON COLUMN growth_phase.ec_target_min IS 'mS/cm pada 25 C. Arsitektur-Sistem.md s12: 1,5-2,0.';
COMMENT ON COLUMN growth_phase.ratio_n IS 'Rasio N:P:K per fase, P dinormalkan 1 (mis. vegetatif 5,4 : 1 : 6,3).';

CREATE INDEX idx_phase_cycle_start ON growth_phase (cycle_id, start_hst);

-- ---------------------------------------------------------------------------
-- Tanaman: dari placeholder menjadi unit penelitian
-- ---------------------------------------------------------------------------
ALTER TABLE plant
    ADD COLUMN cycle_id         BIGINT,
    ADD COLUMN treatment_code   VARCHAR(16),
    ADD COLUMN block_code       VARCHAR(16),
    ADD COLUMN row_code         VARCHAR(16),
    ADD COLUMN plot_code        VARCHAR(8),
    ADD COLUMN station_code     VARCHAR(32),
    ADD COLUMN position_in_row  INTEGER,
    ADD COLUMN comparison_group VARCHAR(16),
    ADD COLUMN tagged_leaves    VARCHAR(64),
    ADD COLUMN active           BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN metadata         JSONB,
    ADD CONSTRAINT fk_plant_cycle FOREIGN KEY (cycle_id) REFERENCES planting_cycle (id);

COMMENT ON COLUMN plant.treatment_code IS 'Protokol-Data.md s2: K0 (kontrol), N-, P-, K- (20% unsur itu). NULL = tanaman produksi biasa.';
COMMENT ON COLUMN plant.block_code IS 'Blok acak sepanjang rel, mis. B1..B4.';
COMMENT ON COLUMN plant.plot_code IS 'Sensor tanah mana yang mewakili galon ini: A -> soil_a.*, B -> soil_b.*';
COMMENT ON COLUMN plant.station_code IS 'Stasiun kamera terdekat, mis. ST-03. Pemetaan stasiun -> tanaman milik tim hardware.';
COMMENT ON COLUMN plant.comparison_group IS 'Protokol-Data.md s6: FERTIMATA (baris 1 & 3), SIMONKORI (baris 2 & 4), atau NONE.';
COMMENT ON COLUMN plant.tagged_leaves IS 'Daun yang diberi label plastik, mis. "1,3,5".';

CREATE INDEX idx_plant_cycle_treatment ON plant (cycle_id, treatment_code);
CREATE INDEX idx_plant_station ON plant (station_code);

-- ---------------------------------------------------------------------------
-- Pengamatan manual per tanaman (tiap 3-4 hari)
-- ---------------------------------------------------------------------------
CREATE TABLE plant_observation (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id        BIGINT        NOT NULL,
    observed_at     TIMESTAMPTZ   NOT NULL,
    hst             INTEGER,
    height_cm       NUMERIC(6, 1),
    leaf_count      INTEGER,
    leaf3_length_cm NUMERIC(6, 1),
    leaf3_width_cm  NUMERIC(6, 1),
    visual_notes    VARCHAR(1000),
    soil_snapshot   JSONB,
    observed_by     BIGINT,
    created_at      TIMESTAMPTZ   NOT NULL,
    CONSTRAINT fk_observation_plant FOREIGN KEY (plant_id) REFERENCES plant (id) ON DELETE CASCADE,
    CONSTRAINT fk_observation_user FOREIGN KEY (observed_by) REFERENCES app_user (id)
);

COMMENT ON TABLE plant_observation IS 'Protokol-Data.md s2 "Dokumentasi wajib per tanaman perlakuan", irama 3-4 hari.';
COMMENT ON COLUMN plant_observation.hst IS 'Dihitung saat dicatat dari transplant_date siklus tanaman.';
COMMENT ON COLUMN plant_observation.soil_snapshot IS 'Pembacaan soil_<plot>.* terakhir saat pengamatan dicatat: {metricKey: {value, unit, recordedAt}}.';

CREATE INDEX idx_observation_plant_observed ON plant_observation (plant_id, observed_at DESC);
