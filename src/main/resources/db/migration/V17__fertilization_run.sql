-- Pemupukan otomatis (keputusan 2 Nov 2026): mengikuti aturan main layanan AI (repo Fertigation_Service).
-- - Jarak hari diambil dari jadwal dosing AI (GET /api/schedule/fertilization, interval_days).
-- - Dosing dilakukan pada sesi siram pertama yang jatuh tempo (komentar DosingSchedule di models.py AI).
-- - Durasi pompa N/P/K dari fuzzy fertigasi AI (POST /api/fuzzy_sys/run_fertilization).
-- Layanan AI tidak menjalankan apa pun, jadi backend yang menjalankan: pompa aduk menyala, pompa N -> P -> K
-- bergantian, aduk sampai selesai, lalu siram sesi itu. Satu baris = satu percobaan pemupukan.
CREATE TABLE fertilization_run (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_date               DATE         NOT NULL,
    irrigation_schedule_id BIGINT,
    status                 VARCHAR(16)  NOT NULL,
    step                   VARCHAR(16),
    next_action_at         TIMESTAMPTZ,
    reason_code            VARCHAR(64),
    message                VARCHAR(500),
    interval_days          INTEGER,
    ai_nitrogen_seconds    NUMERIC(8, 2),
    ai_phosphorus_seconds  NUMERIC(8, 2),
    ai_potassium_seconds   NUMERIC(8, 2),
    nitrogen_seconds       INTEGER,
    phosphorus_seconds     INTEGER,
    potassium_seconds      INTEGER,
    stirrer_seconds        INTEGER,
    stirrer_command_uid    VARCHAR(64),
    nitrogen_command_uid   VARCHAR(64),
    phosphorus_command_uid VARCHAR(64),
    potassium_command_uid  VARCHAR(64),
    started_at             TIMESTAMPTZ,
    finished_at            TIMESTAMPTZ,
    created_at             TIMESTAMPTZ  NOT NULL,
    updated_at             TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_fertilization_run_schedule FOREIGN KEY (irrigation_schedule_id)
        REFERENCES irrigation_schedule (id) ON DELETE SET NULL
);

CREATE INDEX ix_fertilization_run_date ON fertilization_run (run_date DESC, id DESC);
-- Paling banyak satu pemupukan yang sedang berjalan.
CREATE UNIQUE INDEX uk_fertilization_run_active ON fertilization_run ((TRUE)) WHERE step IS NOT NULL;

COMMENT ON TABLE fertilization_run IS 'Percobaan pemupukan otomatis; jatuh tempo = DONE/PARTIAL terakhir + interval_days AI.';
COMMENT ON COLUMN fertilization_run.status IS
    'IN_PROGRESS, DONE (dosis AI sudah dituang, termasuk dosis 0), PARTIAL (sebagian pompa sempat jalan, dihitung sudah dipupuk agar tidak dobel), SKIPPED (tidak dituang: data sensor basi, pompa tidak ada), FAILED (tidak dituang: AI tidak bisa dipakai, perintah ditolak, backend mati).';
COMMENT ON COLUMN fertilization_run.step IS 'Langkah berikutnya: PHOSPHORUS, POTASSIUM, MIXING, IRRIGATE; null = selesai.';
COMMENT ON COLUMN fertilization_run.irrigation_schedule_id IS 'Sesi siram yang menunggu pemupukan ini selesai.';
COMMENT ON COLUMN fertilization_run.ai_nitrogen_seconds IS 'Durasi dari AI sebelum dibatasi max_run_seconds pompa.';
