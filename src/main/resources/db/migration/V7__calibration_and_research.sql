-- Fase 3: kalibrasi & catatan penelitian (Protokol-Data.md §6-§8).
--
-- Prinsip yang dijaga semua tabel di bawah: nilai mentah sensor TIDAK pernah diubah. Kalibrasi adalah
-- data terpisah yang dipakai saat membaca (calibratedValue), jadi model regresi bisa diganti kapan
-- saja dan riwayat bisa dihitung ulang. Semua tabel append-only: kalibrasi baru = baris baru.

-- ---------------------------------------------------------------------------
-- Sampel lab berpasangan (Protokol §7 langkah 1-2)
-- ---------------------------------------------------------------------------
CREATE TABLE calibration_sample (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id     BIGINT         NOT NULL,
    sampled_at    TIMESTAMPTZ    NOT NULL,
    sensor_value  NUMERIC(18, 6) NOT NULL,
    lab_value     NUMERIC(18, 6) NOT NULL,
    lab_method    VARCHAR(64),
    covariates    JSONB,
    sample_code   VARCHAR(64),
    notes         VARCHAR(500),
    recorded_by   BIGINT,
    created_at    TIMESTAMPTZ    NOT NULL,
    CONSTRAINT fk_cal_sample_sensor FOREIGN KEY (sensor_id) REFERENCES sensor (id) ON DELETE CASCADE,
    CONSTRAINT fk_cal_sample_user FOREIGN KEY (recorded_by) REFERENCES app_user (id)
);

COMMENT ON TABLE calibration_sample IS 'Protokol-Data.md s7: pembacaan sensor in-situ berpasangan dengan hasil uji lab dari titik yang sama.';
COMMENT ON COLUMN calibration_sample.sensor_value IS 'Nilai mentah sensor saat sampel diambil (diisi operator atau diambil dari pembacaan terdekat).';
COMMENT ON COLUMN calibration_sample.lab_method IS 'Mis. Kjeldahl, Olsen-P, Bray-1, NH4OAc 1N + AAS, H2O 1:2,5, ekstrak 1:5.';
COMMENT ON COLUMN calibration_sample.covariates IS 'metricKey -> nilai kovariat saat sampel diambil, mis. {"soil_a.moisture": 41.2, "soil_a.temperature": 27.5}.';

CREATE INDEX idx_cal_sample_sensor ON calibration_sample (sensor_id, sampled_at DESC);

-- ---------------------------------------------------------------------------
-- Model kalibrasi sensor (Protokol §7 langkah 3-4)
-- ---------------------------------------------------------------------------
CREATE TABLE sensor_calibration (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id         BIGINT         NOT NULL,
    method            VARCHAR(16)    NOT NULL,
    intercept         NUMERIC(18, 8) NOT NULL,
    slope             NUMERIC(18, 8) NOT NULL,
    covariates        JSONB,
    valid_from        TIMESTAMPTZ    NOT NULL,
    sample_count      INTEGER,
    r_squared         NUMERIC(18, 6),
    rmse              NUMERIC(18, 6),
    mae               NUMERIC(18, 6),
    bias              NUMERIC(18, 6),
    loa_lower         NUMERIC(18, 6),
    loa_upper         NUMERIC(18, 6),
    notes             VARCHAR(500),
    created_by        BIGINT,
    created_at        TIMESTAMPTZ    NOT NULL,
    CONSTRAINT fk_sensor_cal_sensor FOREIGN KEY (sensor_id) REFERENCES sensor (id) ON DELETE CASCADE,
    CONSTRAINT fk_sensor_cal_user FOREIGN KEY (created_by) REFERENCES app_user (id)
);

COMMENT ON TABLE sensor_calibration IS 'calibrated = intercept + slope * raw + sum(coef_i * covariate_i). Berlaku untuk pembacaan dengan recorded_at >= valid_from sampai kalibrasi berikutnya.';
COMMENT ON COLUMN sensor_calibration.method IS 'LINEAR (tanpa kovariat) atau REGRESSION (dengan kovariat kelembapan/suhu).';
COMMENT ON COLUMN sensor_calibration.covariates IS 'metricKey -> koefisien, mis. {"soil_a.moisture": -0.42}. Nilai kovariat diambil dari pesan telemetri yang sama.';
COMMENT ON COLUMN sensor_calibration.bias IS 'Bland-Altman: rata-rata (kalibrasi - lab). loa_lower/upper = bias -/+ 1,96 SD.';

CREATE INDEX idx_sensor_cal_sensor_valid ON sensor_calibration (sensor_id, valid_from DESC);

-- ---------------------------------------------------------------------------
-- Uji drift mingguan (Protokol §7 langkah 5)
-- ---------------------------------------------------------------------------
CREATE TABLE sensor_drift_check (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id         BIGINT         NOT NULL,
    checked_at        TIMESTAMPTZ    NOT NULL,
    standard_name     VARCHAR(64)    NOT NULL,
    reference_value   NUMERIC(18, 6) NOT NULL,
    measured_value    NUMERIC(18, 6) NOT NULL,
    deviation         NUMERIC(18, 6) NOT NULL,
    deviation_percent NUMERIC(10, 4),
    probe_cleaned     BOOLEAN        NOT NULL DEFAULT FALSE,
    notes             VARCHAR(500),
    performed_by      BIGINT,
    created_at        TIMESTAMPTZ    NOT NULL,
    CONSTRAINT fk_drift_sensor FOREIGN KEY (sensor_id) REFERENCES sensor (id) ON DELETE CASCADE,
    CONSTRAINT fk_drift_user FOREIGN KEY (performed_by) REFERENCES app_user (id)
);

COMMENT ON TABLE sensor_drift_check IS 'Probe direndam larutan standar (EC 1413 uS/cm; buffer pH 4,01 / 6,86). deviation = measured - reference.';

CREATE INDEX idx_drift_sensor_checked ON sensor_drift_check (sensor_id, checked_at DESC);

-- ---------------------------------------------------------------------------
-- Kalibrasi debit pompa peristaltik (Protokol §8)
-- ---------------------------------------------------------------------------
CREATE TABLE actuator_calibration (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actuator_id         BIGINT         NOT NULL,
    calibrated_at       TIMESTAMPTZ    NOT NULL,
    flow_ml_per_second  NUMERIC(12, 6) NOT NULL,
    trial_count         INTEGER        NOT NULL,
    trials              JSONB,
    flow_cv_percent     NUMERIC(8, 4),
    bus_voltage         NUMERIC(8, 2),
    notes               VARCHAR(500),
    performed_by        BIGINT,
    created_at          TIMESTAMPTZ    NOT NULL,
    CONSTRAINT fk_act_cal_actuator FOREIGN KEY (actuator_id) REFERENCES actuator (id) ON DELETE CASCADE,
    CONSTRAINT fk_act_cal_user FOREIGN KEY (performed_by) REFERENCES app_user (id),
    CONSTRAINT ck_act_cal_flow_positive CHECK (flow_ml_per_second > 0)
);

COMMENT ON TABLE actuator_calibration IS 'Gelas ukur + stopwatch, minimal 3 ulangan. Selang silikon melar, jadi rekalibrasi bulanan.';
COMMENT ON COLUMN actuator_calibration.trials IS '[{"durationSeconds": 30, "volumeMl": 61.5}, ...] bila ulangan dicatat satu per satu.';
COMMENT ON COLUMN actuator_calibration.bus_voltage IS 'Tegangan saat kalibrasi; debit pompa berubah dengan tegangan.';

CREATE INDEX idx_act_cal_actuator ON actuator_calibration (actuator_id, calibrated_at DESC);

-- Volume pupuk = durasi perintah EXECUTED x debit; query ini menyaring per aktuator dan rentang waktu.
CREATE INDEX IF NOT EXISTS idx_command_actuator_status_requested
    ON actuator_command (actuator_id, status, requested_at);

-- ---------------------------------------------------------------------------
-- Data panen per tanaman (Protokol §6)
-- ---------------------------------------------------------------------------
CREATE TABLE harvest_record (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id             BIGINT        NOT NULL,
    harvested_on         DATE          NOT NULL,
    hst                  INTEGER,
    fruit_weight_g       NUMERIC(8, 1),
    brix                 NUMERIC(5, 2),
    firmness             NUMERIC(8, 2),
    firmness_unit        VARCHAR(16),
    flesh_thickness_mm   NUMERIC(6, 1),
    dry_matter_percent   NUMERIC(5, 2),
    notes                VARCHAR(1000),
    recorded_by          BIGINT,
    created_at           TIMESTAMPTZ   NOT NULL,
    CONSTRAINT fk_harvest_plant FOREIGN KEY (plant_id) REFERENCES plant (id) ON DELETE CASCADE,
    CONSTRAINT fk_harvest_user FOREIGN KEY (recorded_by) REFERENCES app_user (id)
);

COMMENT ON TABLE harvest_record IS 'Protokol-Data.md s6 "Saat panen": bobot, Brix, kekerasan, tebal daging, bahan kering. Satu baris per buah.';
COMMENT ON COLUMN harvest_record.firmness_unit IS 'Satuan penetrometer, mis. N atau kgf.';

CREATE INDEX idx_harvest_plant ON harvest_record (plant_id, harvested_on DESC);
