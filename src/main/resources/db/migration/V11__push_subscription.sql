-- Langganan Web Push: satu baris per browser/HP yang mengizinkan notifikasi.
--
-- endpoint adalah URL unik dari server push (Google/Mozilla/Apple) untuk browser itu; p256dh dan auth
-- adalah kunci yang dipakai mengenkripsi isi notifikasi untuk browser tersebut (RFC 8291). Baris ikut
-- terhapus bila akunnya dihapus.
CREATE TABLE push_subscription (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT        NOT NULL,
    endpoint        VARCHAR(1024) NOT NULL,
    p256dh          VARCHAR(128)  NOT NULL,
    auth            VARCHAR(64)   NOT NULL,
    user_agent      VARCHAR(255),
    last_success_at TIMESTAMPTZ,
    failure_count   INTEGER       NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ   NOT NULL,
    updated_at      TIMESTAMPTZ   NOT NULL,
    CONSTRAINT fk_push_subscription_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT uk_push_subscription_endpoint UNIQUE (endpoint)
);

COMMENT ON TABLE push_subscription IS 'Browsers that accepted push notifications. Removed when the push service answers 404/410.';

CREATE INDEX idx_push_subscription_user ON push_subscription (user_id);
