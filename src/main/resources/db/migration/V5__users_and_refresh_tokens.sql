-- Fase 2: manajemen pengguna, peran, dan sesi 7 hari lewat refresh token.
--
-- Peran disimpan sebagai teks (ADMIN / OPERATOR / VIEWER); hierarkinya ditegakkan di aplikasi.
-- Akun paling lama (id terkecil, yaitu akun bootstrap) dinaikkan menjadi ADMIN agar ada yang bisa
-- mengelola pengguna setelah migrasi ini. Akun lain tetap OPERATOR.

ALTER TABLE app_user
    ADD COLUMN must_change_password BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN app_user.must_change_password IS 'TRUE setelah sandi di-reset admin atau akun dibuat; aplikasi meminta ganti sandi saat masuk.';

UPDATE app_user SET role = 'ADMIN' WHERE id = (SELECT min(id) FROM app_user);

-- ---------------------------------------------------------------------------
-- Refresh token: akses tetap 60 menit (JWT), sesi diperpanjang diam-diam sampai 7 hari.
-- Hanya hash SHA-256 yang disimpan; nilai mentah hanya ada di klien.
-- ---------------------------------------------------------------------------
CREATE TABLE refresh_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    token_hash VARCHAR(64)  NOT NULL,
    expires_at TIMESTAMPTZ  NOT NULL,
    revoked_at TIMESTAMPTZ,
    user_agent VARCHAR(255),
    created_at TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_refresh_token_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT uk_refresh_token_hash UNIQUE (token_hash)
);

COMMENT ON TABLE refresh_token IS 'Satu baris per sesi perangkat. Dirotasi setiap kali dipakai; yang lama di-revoke.';

CREATE INDEX idx_refresh_token_user ON refresh_token (user_id);
CREATE INDEX idx_refresh_token_expires ON refresh_token (expires_at);
