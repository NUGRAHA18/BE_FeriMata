-- 4 Nov 2026: takaran pupuk hybrid. Bawaan takaran N/P/K dari fuzzy AI (run_fertilization); petani boleh
-- mengisi takaran sendiri dalam mililiter. Backend mengubahnya ke detik dengan kalibrasi debit pompa terbaru.
-- Jarak hari tetap dari jadwal dosing AI. Aturan S9 (EC/pH drum basi = tidak dosing) tetap berlaku di kedua mode.

CREATE TABLE fertilization_dose_setting (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode          VARCHAR(16)   NOT NULL,
    nitrogen_ml   NUMERIC(8, 2),
    phosphorus_ml NUMERIC(8, 2),
    potassium_ml  NUMERIC(8, 2),
    updated_by    VARCHAR(64),
    created_at    TIMESTAMPTZ   NOT NULL,
    updated_at    TIMESTAMPTZ   NOT NULL,
    CONSTRAINT ck_fertilization_dose_setting_mode CHECK (mode IN ('AI', 'MANUAL'))
);
-- Satu baris saja; belum ada baris = mode AI.
CREATE UNIQUE INDEX uk_fertilization_dose_setting_single ON fertilization_dose_setting ((TRUE));

COMMENT ON TABLE fertilization_dose_setting IS 'Takaran pupuk: AI (bawaan) atau MANUAL (ml isian petani). Belum ada baris = AI.';
COMMENT ON COLUMN fertilization_dose_setting.nitrogen_ml IS
    'Takaran isian petani; tetap disimpan saat kembali ke mode AI agar tidak perlu diketik ulang.';

